#pragma once
// Журнал змін стану мережі: останні MAINS_LOG_SIZE переходів із часом. Зберігається лише в RAM:
// після перезапуску ESP історія не відновлюється, журнал починається з поточного стану.
// Усі функції викликаються лише з loop() — без блокувань.

#include <Arduino.h>
#include <ArduinoJson.h>

namespace mainslog {

// Починає журнал заново з поточного стану (перший запис).
void begin(bool currentOn);

// Перехід у стан on, що стався в момент eventMs (millis()). Мітка часу тимчасова (годинник ESP або 0), одразу
// просимо в timesync позачергову синхронізацію; tick() уточнить мітку від свіжого часу сервісу.
void record(bool on, uint32_t eventMs);
// Уточнює мітки очікуючих записів після синхронізації годинника.
void tick();
uint32_t version();         // збільшується при кожній зміні вмісту — щоб не слати масив щосекунди

// Найновіші першими: [[ts, on], …]; ts = 0 — час невідомий.
void toJson(JsonArray out);

}  // namespace mainslog
